#!/usr/bin/env python3
"""
Generate Data/VanillaQuestIDs.lua from Questie's Classic quest DB.
The scanner uses these ids as canaries: a vanilla quest that stays silent
means the server is throttling us; an unknown id that stays silent simply
does not exist.

    python tools/gen_vanilla_ids.py [--questie <folder>]
"""
import argparse
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from questie_lookup import load_db, QUEST_KEYS, DEFAULT_QUESTIE  # noqa: E402


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--questie", default=os.environ.get("QUESTIE", DEFAULT_QUESTIE))
    args = ap.parse_args()
    db = load_db(os.path.join(args.questie, "Database", "Classic", "classicQuestDB.lua"), QUEST_KEYS)
    ids = sorted(db)
    out = os.path.join(os.path.dirname(HERE), "Data", "VanillaQuestIDs.lua")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    lines = ["-- AUTO-GENERATED by tools/gen_vanilla_ids.py from Questie's classicQuestDB.lua - DO NOT EDIT",
             "-- %d vanilla quest ids, used by Scanner.lua as throttle canaries." % len(ids),
             "local _, ns = ...",
             "ns.VanillaQuestIDs = {"]
    for i in range(0, len(ids), 25):
        lines.append("    " + ", ".join(str(x) for x in ids[i:i + 25]) + ",")
    lines.append("}")
    with open(out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"wrote {len(ids)} ids to {out}")


if __name__ == "__main__":
    main()
